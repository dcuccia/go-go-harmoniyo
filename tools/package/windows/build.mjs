#!/usr/bin/env node
// Builds the portable Windows download-and-play package of Go Go HarmoniYo (issue #43):
//
//   node tools/package/windows/build.mjs [--version 0.1.0] [--skip-zip]
//
// Needs Windows x64, Node 22 and `npm ci` in spikes/i2-web-phones, spikes/s1-phone-bell and
// tools/package/windows. Output in tools/package/windows/out/ (gitignored):
//   go-go-harmoniyo-<version>-windows-x64.zip   the download (one folder, GoGoHarmoniYo\)
//   SHA256SUMS.txt                               checksums to publish next to it
//   stage/GoGoHarmoniYo/                         the unzipped package (run it from here to test)
// See README.md in this folder for the layout and how the exe works.
import { execFileSync, spawnSync } from 'node:child_process';
import { createHash } from 'node:crypto';
import { cpSync, existsSync, mkdirSync, readdirSync, readFileSync, rmSync, statSync, writeFileSync } from 'node:fs';
import { createRequire } from 'node:module';
import { dirname, join, relative } from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';
import { bundleNotices, packageDirOf, packagesFromMetafile } from '../../licensing/lib/bundle.mjs';

const here = dirname(fileURLToPath(import.meta.url));
const repo = join(here, '..', '..', '..');
const i2 = join(repo, 'spikes', 'i2-web-phones');
const s1 = join(repo, 'spikes', 's1-phone-bell');
const out = join(here, 'out');
const cache = join(out, 'cache');
const work = join(out, 'work');
const PACKAGE_DIR = 'GoGoHarmoniYo';
const stage = join(out, 'stage', PACKAGE_DIR);
const app = join(stage, 'app');
const EXE = 'go-go-harmoniyo.exe';
const SEA_FUSE = 'NODE_SEA_FUSE_fce680ab2cc467b6e072b8b5df1996b2';

const arg = (name) => {
  const i = process.argv.indexOf(`--${name}`);
  return i > 0 ? process.argv[i + 1] : undefined;
};
const git = (...a) => execFileSync('git', a, { cwd: repo, encoding: 'utf8' }).trim();
const commit = git('rev-parse', '--short=12', 'HEAD');
const tag = process.env.GITHUB_REF_TYPE === 'tag' ? process.env.GITHUB_REF_NAME : undefined;
const version = (arg('version') ?? tag ?? `0.0.0-dev.${commit}`).replace(/^v/, '');
if (!/^[\w.+-]+$/.test(version)) throw new Error(`bad version "${version}"`);
const zipName = `go-go-harmoniyo-${version}-windows-x64.zip`;

const t0 = Date.now();
const step = (s) => console.log(`\n▸ ${s}  (${((Date.now() - t0) / 1000).toFixed(1)} s)`);
const sha256 = (buf) => createHash('sha256').update(buf).digest('hex');
const fail = (msg) => {
  console.error(`\n✗ ${msg}`);
  process.exit(1);
};

if (process.platform !== 'win32' || process.arch !== 'x64') fail('Build the Windows package on Windows x64 (the SEA blob is generated by the pinned node.exe).');
for (const d of [i2, s1, here]) if (!existsSync(join(d, 'node_modules'))) fail(`Run \`npm ci\` in ${relative(repo, d)} first.`);

const { binaries } = JSON.parse(readFileSync(join(here, 'binaries.json'), 'utf8'));
const node = binaries.find((b) => b.file === 'node.exe');
if (`v${node.version}`.split('.')[0] !== process.version.split('.')[0]) {
  console.warn(`! Building with Node ${process.version}; the package runs Node ${node.version}.`);
}

/** Download once into out/cache/ and refuse anything that doesn't match the pinned hash. */
async function pinned(url, hash, name) {
  const file = join(cache, `${hash.slice(0, 12)}-${name}`);
  if (existsSync(file) && sha256(readFileSync(file)) === hash) return file;
  console.log(`  downloading ${url}`);
  const res = await fetch(url);
  if (!res.ok) fail(`${url}: HTTP ${res.status}`);
  const buf = Buffer.from(await res.arrayBuffer());
  const got = sha256(buf);
  if (got !== hash) fail(`${url}: SHA-256 ${got} does not match the pin ${hash} (tools/package/windows/binaries.json)`);
  writeFileSync(file, buf);
  return file;
}

function run(cmd, args, cwd) {
  const r = spawnSync(cmd, args, { cwd, stdio: 'inherit' });
  if (r.status !== 0) fail(`${[cmd, ...args].join(' ')} failed (exit ${r.status ?? r.signal})`);
}

const packages = new Map(); // npm package dir → bundles it went into

// ── 1. pinned binaries and their license texts ─────────────────────────────────────────────────
step('Pinned binaries');
mkdirSync(cache, { recursive: true });
for (const b of binaries) {
  b.path = await pinned(b.url, b.sha256, b.file);
  b.text = readFileSync(await pinned(b.licenseText.url, b.licenseText.sha256, `${b.file}.LICENSE.txt`), 'utf8');
  console.log(`  ${b.name} ${b.version} (${b.license}) ✓ sha256 ${b.sha256.slice(0, 16)}…`);
}

rmSync(join(out, 'stage'), { recursive: true, force: true });
rmSync(work, { recursive: true, force: true });
mkdirSync(app, { recursive: true });
mkdirSync(work, { recursive: true });

// ── 2. the game (I2, Vite) → app/game ──────────────────────────────────────────────────────────
step('Game (spikes/i2-web-phones: charts, brand, vite build)');
run(process.execPath, ['scripts/build-charts.mjs'], i2);
run(process.execPath, ['scripts/brand-assets.mjs'], i2);
// Vite's ESM entry (its CJS API is deprecated); esbuild and postject are CommonJS.
const vite = await import(pathToFileURL(join(dirname(createRequire(join(i2, 'package.json')).resolve('vite/package.json')), 'dist', 'node', 'index.js')).href);
await vite.build({
  root: i2,
  configFile: join(i2, 'vite.config.ts'),
  logLevel: 'warn',
  build: { outDir: join(app, 'game'), emptyOutDir: true, reportCompressedSize: false },
  plugins: [{
    name: 'go-go-harmoniyo-license-inventory',
    generateBundle(_, bundle) {
      for (const chunk of Object.values(bundle)) {
        for (const id of chunk.type === 'chunk' ? chunk.moduleIds : []) {
          const dir = packageDirOf(id.replace(/^\0/, '').split('?')[0]);
          if (dir) packages.set(dir, (packages.get(dir) ?? new Set()).add('game'));
        }
      }
    },
  }],
});

// ── 3. the phone controller pages (S1, esbuild) → app/controller ───────────────────────────────
// Same options as buildWeb() in spikes/s1-phone-bell/src/host/server.ts (which skips this when packaged).
step('Phone controller (spikes/s1-phone-bell/src/web)');
const esbuild = createRequire(join(s1, 'package.json'))('esbuild');
const web = join(s1, 'src', 'web');
const controller = await esbuild.build({
  entryPoints: { controller: join(web, 'controller.ts'), dashboard: join(web, 'dashboard.ts'), meter: join(web, 'meter.ts') },
  bundle: true,
  format: 'esm',
  target: ['es2020', 'safari15', 'chrome100'],
  outdir: join(app, 'controller', 'dist'),
  metafile: true,
  logLevel: 'warning',
  absWorkingDir: repo,
});
packagesFromMetafile(controller.metafile, 'controller', repo, packages);
for (const f of readdirSync(web).filter((f) => !f.endsWith('.ts'))) cpSync(join(web, f), join(app, 'controller', f));

// ── 4. brand files (the host serves them at /brand/) ───────────────────────────────────────────
step('Brand files');
const brand = join(repo, 'docs', 'design', 'brand');
const brandFile = (f) => /^[\w-]+\.(svg|png|ico)$/.test(f);
mkdirSync(join(app, 'brand', 'yo'), { recursive: true });
for (const f of readdirSync(brand).filter(brandFile)) cpSync(join(brand, f), join(app, 'brand', f));
for (const f of readdirSync(join(brand, 'yo')).filter(brandFile)) cpSync(join(brand, 'yo', f), join(app, 'brand', 'yo', f));

// ── 5. the launcher + host as one CommonJS script ─────────────────────────────────────────────
// SEA runs a single CommonJS script whose require() only loads built-in modules, so everything,
// including werift (WebRTC), is bundled. launch.mjs uses import.meta.url at top level; in CJS it
// becomes the bundle's own file URL (only used for dev paths that the packaged mode doesn't take).
step('Launcher + phone host bundle (esbuild → CommonJS)');
const seaJs = join(work, 'sea.cjs');
const sea = await esbuild.build({
  entryPoints: [join(here, 'sea-main.mjs')],
  bundle: true,
  platform: 'node',
  format: 'cjs',
  target: 'node22',
  outfile: seaJs,
  nodePaths: [join(s1, 'node_modules'), join(i2, 'node_modules')],
  // ws's optional native helpers and esbuild (dev-only web build) stay out.
  external: ['esbuild', 'bufferutil', 'utf-8-validate'],
  define: { 'import.meta.url': '__gogoImportMetaUrl' },
  banner: { js: "var __gogoImportMetaUrl = require('url').pathToFileURL(__filename).href;" },
  legalComments: 'none',
  metafile: true,
  logLevel: 'warning',
  absWorkingDir: repo,
});
packagesFromMetafile(sea.metafile, 'host', repo, packages);
console.log(`  ${(statSync(seaJs).size / 1e6).toFixed(1)} MB`);

// ── 6. license gate for what was bundled → THIRD_PARTY_NOTICES.md ─────────────────────────────
step('License gate (bundled packages and binaries)');
const extraTexts = {};
for (const [id, t] of Object.entries(JSON.parse(readFileSync(join(here, 'license-texts.json'), 'utf8')).packages)) {
  extraTexts[id] = { url: t.url, text: readFileSync(await pinned(t.url, t.sha256, `${id.replace(/[^\w.@-]/g, '_')}.LICENSE.txt`), 'utf8') };
}
const notices = bundleNotices({ packages, binaries, extraTexts, scope: 'tools/package/windows', title: `Go Go HarmoniYo ${version} for Windows` });
for (const r of notices.rows) console.log(`  ${r.name}@${r.version}  ${r.license}  [${r.bundles.join(', ')}]`);
if (notices.errors.length) fail(`License gate failed:\n  ${notices.errors.join('\n  ')}`);
writeFileSync(join(stage, 'THIRD_PARTY_NOTICES.md'), notices.markdown + '\n');

// ── 7. go-go-harmoniyo.exe: node.exe + the bundle (Node SEA, postject) ──────────────────────────
step(`${EXE} (Node ${node.version} single executable application)`);
const blob = join(work, 'sea-prep.blob');
writeFileSync(join(work, 'sea-config.json'), JSON.stringify({ main: seaJs, output: blob, disableExperimentalSEAWarning: true }));
// The blob must come from the same Node version that runs it: use the pinned node.exe.
run(node.path, ['--experimental-sea-config', join(work, 'sea-config.json')], work);
const exe = join(stage, EXE);
cpSync(node.path, exe);
// node.exe is Authenticode-signed by the OpenJS Foundation; injecting invalidates that signature,
// so strip it when signtool is available (README.md: code signing is an open question).
const signtool = findSigntool();
if (signtool) run(signtool, ['remove', '/s', exe], work);
else console.warn('  ! signtool not found: the exe keeps node.exe\'s (now invalid) signature block');
const { inject } = createRequire(join(here, 'package.json'))('postject');
await inject(exe, 'NODE_SEA_BLOB', readFileSync(blob), { sentinelFuse: SEA_FUSE });

// ── 8. everything else in the folder ───────────────────────────────────────────────────────────
step('Package folder');
const cf = binaries.find((b) => b.file === 'cloudflared.exe');
cpSync(cf.path, join(stage, 'cloudflared.exe'));
cpSync(join(here, 'Play Go Go HarmoniYo.cmd'), join(stage, 'Play Go Go HarmoniYo.cmd'));
cpSync(join(repo, 'LICENSE'), join(stage, 'LICENSE.txt'));
cpSync(join(repo, 'ATTRIBUTION.md'), join(stage, 'ATTRIBUTION.md'));
mkdirSync(join(stage, 'LICENSES'));
// Texts of the licenses our code and assets use (LGPL is only for fetched YARG sources, not shipped).
for (const f of readdirSync(join(repo, 'LICENSES')).filter((f) => !f.startsWith('LGPL'))) cpSync(join(repo, 'LICENSES', f), join(stage, 'LICENSES', f));
const buildInfo = { product: 'Go Go HarmoniYo', version, commit, built: new Date().toISOString(), node: node.version, cloudflared: cf.version };
writeFileSync(join(app, 'build-info.json'), JSON.stringify(buildInfo, null, 2) + '\n');
writeFileSync(join(stage, 'README.txt'), readFileSync(join(here, 'README.txt'), 'utf8')
  .replace('{{VERSION}}', version).replace('{{COMMIT}}', commit).replace(/\r?\n/g, '\r\n'));

// ── 9. zip + checksums ─────────────────────────────────────────────────────────────────────────
const zip = join(out, zipName);
rmSync(zip, { force: true });
for (const f of readdirSync(out).filter((f) => f.endsWith('.zip') || f === 'SHA256SUMS.txt')) rmSync(join(out, f));
if (!process.argv.includes('--skip-zip')) {
  step('Zip and checksums');
  // bsdtar ships with Windows 10 1803+ and on the GitHub runners; -a picks the format from .zip.
  run(join(process.env.SystemRoot ?? 'C:\\Windows', 'System32', 'tar.exe'), ['-a', '-c', '-f', zip, PACKAGE_DIR], join(out, 'stage'));
  writeFileSync(join(out, 'SHA256SUMS.txt'), `${sha256(readFileSync(zip))}  ${zipName}\n`);
}

const size = (p) => `${(statSync(p).size / 1e6).toFixed(1)} MB`;
console.log(`\n✓ Go Go HarmoniYo ${version} (${commit}) for Windows in ${((Date.now() - t0) / 1000).toFixed(0)} s`);
console.log(`  ${relative(repo, exe)}  ${size(exe)}`);
if (existsSync(zip)) {
  console.log(`  ${relative(repo, zip)}  ${size(zip)}`);
  console.log(`  ${relative(repo, join(out, 'SHA256SUMS.txt'))}: ${readFileSync(join(out, 'SHA256SUMS.txt'), 'utf8').trim()}`);
}
if (process.env.GITHUB_OUTPUT) writeFileSync(process.env.GITHUB_OUTPUT, `version=${version}\nzip=${zipName}\n`, { flag: 'a' });

function findSigntool() {
  const kits = join(process.env['ProgramFiles(x86)'] ?? 'C:\\Program Files (x86)', 'Windows Kits', '10', 'bin');
  if (!existsSync(kits)) return null;
  const versions = readdirSync(kits).filter((v) => /^10\./.test(v)).sort((a, b) => b.localeCompare(a, undefined, { numeric: true }));
  for (const v of versions) {
    const p = join(kits, v, 'x64', 'signtool.exe');
    if (existsSync(p)) return p;
  }
  return null;
}
