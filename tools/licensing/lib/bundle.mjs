// License gate and notices for a distributable bundle (ADR-0008): every npm package compiled into
// the bundle must have an allowlisted permissive license (or an exception whose scope covers the
// bundle) and ship a license file; pinned binaries come from binaries.json (checked by
// license-gate.mjs). Produces the package's THIRD_PARTY_NOTICES.md with the full license texts.
// Node built-ins only.
import { existsSync, readFileSync, readdirSync } from 'node:fs';
import { join, sep } from 'node:path';
import { readJson } from './common.mjs';
import { isAllowed, normalizeNpmLicense } from './spdx.mjs';

const LICENSE_FILE = /^(licen[cs]e|copying|notice)([-._].*)?$/i;

/** npm package directory for a bundled module path, or null (our own code). */
export function packageDirOf(modulePath) {
  const p = modulePath.split(/[\\/]/);
  const i = p.lastIndexOf('node_modules');
  if (i < 0 || i + 1 >= p.length) return null;
  const n = p[i + 1].startsWith('@') ? 2 : 1;
  return p.slice(0, i + 1 + n).join(sep);
}

/**
 * @param {object} o
 * @param {Map<string, Set<string>>} o.packages  package dir → names of the bundles it went into
 * @param {Array<{name, version, license, licenseNote?, role?, source?, url, text: string}>} o.binaries
 * @param {string} o.scope  repo path of the package (exceptions must cover it), e.g. tools/package/windows
 * @param {string} o.title
 * @param {Record<string, {url: string, text: string}>} [o.extraTexts]  name@version → pinned upstream
 *   license text, for packages published without a LICENSE file
 */
export function bundleNotices({ packages, binaries = [], scope, title, extraTexts = {} }) {
  const policy = readJson('tools/licensing/policy.json');
  const { exceptions } = readJson('tools/licensing/exceptions.json');
  const isCopyleft = (id) => policy.copyleft.prefixes.some((p) => id.startsWith(p));
  const permissive = new Set(policy.allow.filter((id) => !isCopyleft(id)));
  const errors = [];
  const rows = [];
  const seen = new Set();
  for (const [dir, bundles] of packages) {
    const manifestPath = join(dir, 'package.json');
    if (!existsSync(manifestPath)) {
      errors.push(`${dir}: no package.json`);
      continue;
    }
    const m = JSON.parse(readFileSync(manifestPath, 'utf8'));
    const id = `${m.name}@${m.version}`;
    if (seen.has(id)) continue;
    seen.add(id);
    const license = normalizeNpmLicense(m.license ?? m.licenses);
    let status = 'allowed';
    try {
      if (!license) throw new Error('no license declared');
      if (!isAllowed(license, permissive)) {
        const ex = exceptions.find((e) => e.ecosystem === 'npm' && e.name === m.name && e.license === license &&
          e.scope.some((s) => scope === s || scope.startsWith(s + '/')));
        if (!ex) throw new Error(`license "${license}" is not an allowlisted permissive license and no exception covers ${scope} (copyleft needs a compliance ADR first: ADR-0008 copyleft adoption gate)`);
        status = ex.id;
      }
    } catch (e) {
      errors.push(`npm ${id}: ${e.message}`);
      status = 'denied';
    }
    const files = readdirSync(dir).filter((f) => LICENSE_FILE.test(f)).sort();
    const texts = files.map((f) => ({ file: f, text: readFileSync(join(dir, f), 'utf8').replace(/\r\n/g, '\n').trim() }));
    const extra = extraTexts[id];
    if (extra) texts.push({ file: `LICENSE (not in the npm package; from ${extra.url})`, text: extra.text.replace(/\r\n/g, '\n').trim() });
    if (!texts.length) errors.push(`npm ${id}: no LICENSE/NOTICE file in the package; pin its upstream license text (e.g. tools/package/windows/license-texts.json)`);
    rows.push({ name: m.name, version: m.version, license, status, bundles: [...bundles].sort(), texts,
      homepage: typeof m.repository === 'string' ? m.repository : m.repository?.url ?? m.homepage ?? `https://www.npmjs.com/package/${m.name}` });
  }
  rows.sort((a, b) => a.name.localeCompare(b.name));
  const esc = (s) => String(s).replace(/\|/g, '\\|');
  const fence = (t) => '````text\n' + t + '\n````';
  const md = [
    `# Third-party notices: ${title}`,
    '',
    'Go Go HarmoniYo\'s own code is MIT (see LICENSE). Art, audio, songs and charts are credited in',
    'ATTRIBUTION.md. This file lists the third-party software included in this download, with its',
    'license and the full license text and copyright notices as shipped by each project.',
    'Generated by tools/licensing/lib/bundle.mjs from what the build actually bundled.',
    '',
    `## Programs (${binaries.length})`,
    '',
    '| Program | Version | License | What it does here |',
    '|---|---|---|---|',
    ...binaries.map((b) => `| ${esc(b.name)} | ${b.version} | ${b.license} | ${esc(b.role ?? '')} |`),
    '',
    `## npm packages compiled into the game, the controller and the host (${rows.length})`,
    '',
    '| Package | Version | License | Bundled into |',
    '|---|---|---|---|',
    ...rows.map((r) => `| ${esc(r.name)} | ${r.version} | ${esc(r.license)}${r.status !== 'allowed' ? ` (${r.status})` : ''} | ${r.bundles.join(', ')} |`),
    '',
    '## License texts',
    '',
    ...binaries.flatMap((b) => [`### ${b.name} ${b.version}`, '', `Source: ${b.source ?? b.url}`, '', ...(b.licenseNote ? [b.licenseNote, ''] : []), fence(b.text.replace(/\r\n/g, '\n').trim()), '']),
    ...rows.flatMap((r) => [`### ${r.name} ${r.version}`, '', `License: ${r.license}. Source: ${r.homepage}`, '',
      ...r.texts.flatMap((t) => [`${t.file}:`, '', fence(t.text), ''])]),
  ].join('\n');
  return { errors, rows, markdown: md };
}

/** Packages (dir → bundles) from an esbuild metafile's inputs. */
export function packagesFromMetafile(metafile, bundle, cwd, into = new Map()) {
  for (const input of Object.keys(metafile.inputs)) {
    const dir = packageDirOf(join(cwd, input));
    if (dir) into.set(dir, (into.get(dir) ?? new Set()).add(bundle));
  }
  return into;
}
