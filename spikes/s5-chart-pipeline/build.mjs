// Build everything: charts/*.json, exports/<id>/ (CH/YARG notes.mid + song.ini, audition MIDIs),
// results/metrics.md and results/previews.md.
//   node build.mjs [--ringers 3,4,5] [--export-ringers 4]
import { mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';
import { loadSong } from './src/pipeline.mjs';
import { buildChart, buildPart, stringifyChart } from './src/chart.mjs';
import { PROFILES } from './src/assign.mjs';
import { TIERS } from './src/arrange.mjs';
import { exportCloneHero, songIni, exportAudition, asciiPreview } from './src/export.mjs';

const root = dirname(fileURLToPath(import.meta.url));
const arg = (name, def) => {
  const i = process.argv.indexOf(`--${name}`);
  return i > 0 ? process.argv[i + 1] : def;
};
const ringerCounts = arg('ringers', '3,4,5').split(',').map(Number);
const exportRingers = Number(arg('export-ringers', '4'));

const manifest = JSON.parse(readFileSync(join(root, 'songs', 'manifest.json'), 'utf8'));
const write = (rel, data) => {
  const p = join(root, rel);
  mkdirSync(dirname(p), { recursive: true });
  writeFileSync(p, data);
};

const metricRows = [];
const profileAgg = {};
const previews = [];
const summary = [];
const t0 = performance.now();

for (const entry of manifest.songs) {
  const t = performance.now();
  const { score, roleNotes, song } = loadSong(entry, join(root, 'songs'));
  const chart = buildChart({ score, roleNotes, song, ringerCounts, profile: 'handbell' });
  write(`charts/${song.id}.json`, stringifyChart(chart) + '\n');
  const ms = performance.now() - t;

  const ch = exportCloneHero(score, chart, exportRingers);
  write(`exports/${song.id}/notes.mid`, ch.midi);
  write(`exports/${song.id}/song.ini`, songIni(chart, exportRingers));
  for (const tier of TIERS) {
    const part = chart.parts.find((p) => p.difficulty === tier && p.ringerCount === exportRingers);
    write(`exports/${song.id}/audition-${tier}-r${exportRingers}.mid`, exportAudition(score, part));
  }

  const roles = { melody: 0, bass: 0, inner: 0 };
  for (const n of roleNotes) roles[n.role]++;
  summary.push({ song, chart, roles, ms, warnings: ch.warnings });

  for (const p of chart.parts) {
    metricRows.push(`| ${song.id} | ${p.ringerCount} | ${p.difficulty} | ${p.metrics.strikes} | ${p.metrics.distinctBells} | ${p.metrics.maxBellsPerRinger} | ${p.metrics.loadBalance ?? '–'} | ${p.metrics.droppedForPlayability.total} | ${p.metrics.remainingViolations} | ${p.metrics.idleRingers} | ${p.ringers.map((r) => r.label).join(', ')} |`);
  }
  for (const [pid] of Object.entries(PROFILES)) {
    for (const k of ringerCounts) {
      for (const tier of TIERS) {
        const p = buildPart(score, roleNotes, tier, k, pid);
        const key = `${pid}|${k}|${tier}`;
        const a = (profileAgg[key] ||= { clean: 0, songs: 0, violations: 0, dropped: 0, overCap: 0 });
        const over = p.metrics.maxBellsPerRinger > PROFILES[pid].maxBells;
        a.songs++;
        if (!p.metrics.remainingViolations && !over) a.clean++;
        a.violations += p.metrics.remainingViolations;
        a.dropped += p.metrics.droppedForPlayability.total;
        if (over) a.overCap++;
      }
    }
  }
  const p4 = chart.parts.find((p) => p.difficulty === 'hard' && p.ringerCount === 4) || chart.parts[chart.parts.length - 1];
  const e4 = chart.parts.find((p) => p.difficulty === 'easy' && p.ringerCount === 4) || chart.parts[0];
  previews.push(`## ${song.title}\n\nEasy, 4 ringers (first 4 bars):\n\n\`\`\`\n${asciiPreview(score, e4, 4)}\n\`\`\`\n\nHard, 4 ringers (first 4 bars):\n\n\`\`\`\n${asciiPreview(score, p4, 4)}\n\`\`\`\n`);
}

const totalMs = performance.now() - t0;
const md = [
  '# S5 metrics (generated by `node build.mjs`; do not edit)',
  '',
  `Generated ${new Date().toISOString().slice(0, 10)} with Node ${process.version}. Total build time ${Math.round(totalMs)} ms.`,
  '',
  '## Corpus',
  '',
  '| Song | Source | License | Duration (s) | Melody / bass / inner notes | Bell span | Fits handbell set | Build (ms) |',
  '|---|---|---|---|---|---|---|---|',
  ...summary.map(({ song, chart, roles, ms }) => `| ${song.title} | ${song.source.kind} | ${song.license.id} | ${chart.timing.durationSec} | ${roles.melody} / ${roles.bass} / ${roles.inner} | ${chart.bells[0].id}–${chart.bells[chart.bells.length - 1].id} (${chart.bells.length} bells) | ${chart.handbellSet.set ?? 'no'}${chart.handbellSet.transposeSemitones ? ` (transpose ${chart.handbellSet.transposeSemitones > 0 ? '+' : ''}${chart.handbellSet.transposeSemitones})` : ''} | ${Math.round(ms)} |`),
  '',
  '## Charts as generated (profile `handbell`, after playability repair)',
  '',
  'Load balance = max/min strikes across active ringers. Dropped = harmony notes removed for playability. Violations = remaining unplayable spots (melody is never dropped).',
  '',
  '| Song | Ringers | Tier | Strikes | Bells | Max bells/ringer | Load balance | Dropped | Violations | Idle ringers | Assignment |',
  '|---|---|---|---|---|---|---|---|---|---|---|',
  ...metricRows,
  '',
  '## Controller profiles (all songs)',
  '',
  'Each profile re-runs assignment + repair. Cell = `clean songs / total` (no remaining violations and within bell capacity), then Σ violations, Σ dropped harmony notes, songs over bell capacity.',
  '',
  ...Object.entries(PROFILES).map(([id, p]) => `- \`${id}\`: ${p.label} (maxBells ${p.maxBells}, maxSimultaneous ${p.maxSimultaneous}, minRepeat ${p.minRepeatSec}s, minSwitch ${p.minSwitchSec}s, swap ${p.swapSec === Infinity ? 'n/a' : `${p.swapSec}s`})`),
  '',
  '| Profile | Ringers | Easy | Medium | Hard |',
  '|---|---|---|---|---|',
  ...Object.keys(PROFILES).flatMap((pid) => ringerCounts.map((k) => `| ${pid} | ${k} | ${TIERS.map((t) => { const a = profileAgg[`${pid}|${k}|${t}`]; return `${a.clean}/${a.songs} clean; ${a.violations}v ${a.dropped}d${a.overCap ? ` ${a.overCap} over cap` : ''}`; }).join(' | ')} |`)),
  '',
  ...(summary.some((s) => s.warnings.length) ? ['## Export warnings', '', ...summary.flatMap((s) => s.warnings.map((w) => `- ${s.song.id}: ${w}`)), ''] : []),
].join('\n');
write('results/metrics.md', md);
write('results/previews.md', `# Lane previews (generated; do not edit)\n\nLegend: columns are each ringer's bells; M = melody, B = bass, h = harmony; \`-\` marks a bar line row, \`.\` an empty eighth-note slot.\n\n${previews.join('\n')}`);
console.log(`Built ${summary.length} songs in ${Math.round(totalMs)} ms`);
for (const s of summary) console.log(`  ${s.song.id}: ${s.chart.bells.length} bells, ${s.chart.timing.durationSec}s, set ${s.chart.handbellSet.set}`);
