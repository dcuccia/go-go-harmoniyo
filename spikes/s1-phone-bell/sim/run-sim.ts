/**
 * Emulated measurements for spike S1. Prints a Markdown report (and writes sim-results.md).
 *   npm run sim
 * Everything here is synthetic: it validates algorithms and bounds, NOT real phones.
 */
import { writeFileSync } from 'node:fs';
import { ImpactDetector } from '../src/core/impact-detector.ts';
import { matchNearest } from '../src/core/match.ts';
import { DEFAULT_RING_PARAMS, learnAxis, RingDetector, type MotionSample, type RingDetectorParams, type StrikeEvent } from '../src/core/ring-detector.ts';
import { centeredAbs, fmt, summarize } from '../src/core/stats.ts';
import { NET_PROFILES, simulateSync, type DeviceClock } from './netsim.ts';
import { clinkSession, distractorSession, RINGERS, ringSession, SENSOR_100HZ, SENSOR_60HZ, type SensorModel } from './synth.ts';

const out: string[] = [];
const log = (s = '') => out.push(s);

function detectAll(samples: readonly MotionSample[], params: Partial<RingDetectorParams>): StrikeEvent[] {
  const d = new RingDetector(params);
  const evs: StrikeEvent[] = [];
  for (const s of samples) {
    const e = d.push(s);
    if (e) evs.push(e);
  }
  return evs;
}

interface RingEval {
  truth: number;
  detected: number;
  matched: number;
  extra: number;
  errors: number[];
  latency: number[];
}

function evalRings(prof: keyof typeof RINGERS, sensor: SensorModel, params: Partial<RingDetectorParams>, calibrate: boolean, seeds = 4, count = 150): RingEval {
  const res: RingEval = { truth: 0, detected: 0, matched: 0, extra: 0, errors: [], latency: [] };
  for (let k = 0; k < seeds; k++) {
    const sess = ringSession(1000 + k * 17 + prof.length, RINGERS[prof], count, 72 + k * 8, sensor);
    let p = params;
    if (calibrate) {
      // Calibration: the first 8 rings of the session in direction-agnostic mode.
      const calEnd = sess.rings[7] + 300;
      const cal = detectAll(sess.samples.filter((s) => s.t < calEnd), { ...params, axis: null });
      p = { ...params, axis: learnAxis(cal) };
    }
    const evs = detectAll(sess.samples, p);
    const m = matchNearest(sess.rings, evs.map((e) => e.t), 120);
    res.truth += sess.rings.length;
    res.detected += evs.length;
    res.matched += m.pairs.length;
    res.extra += m.extra.length;
    for (const pr of m.pairs) {
      res.errors.push(pr.diff);
      res.latency.push(evs[pr.evIndex].firedAt - sess.rings[pr.refIndex]);
    }
  }
  return res;
}

function distractorFp(sensor: SensorModel, params: Partial<RingDetectorParams>, axis: boolean): { perMin: number; n: number; minutes: number } {
  let n = 0;
  let minutes = 0;
  for (let k = 0; k < 3; k++) {
    const durationMs = 10 * 60_000;
    const d = distractorSession(500 + k, durationMs, sensor);
    // A calibrated axis is fixed in the device frame; distractors have random axes.
    const evs = detectAll(d.samples, axis ? { ...params, axis: [1, 0, 0] } : params);
    n += evs.length;
    minutes += durationMs / 60_000;
  }
  return { perMin: n / minutes, n, minutes };
}

const clocks: Record<string, DeviceClock> = {
  'iPhone-like (1 ms timer, +40 ppm)': { offset: 123_456.7, driftPpm: 40, resolution: 1 },
  'Pixel-like (0.1 ms timer, −25 ppm)': { offset: -98_765.4, driftPpm: -25, resolution: 0.1 },
};

log('# S1 emulated results');
log();
log(`Generated by \`npm run sim\` on ${new Date().toISOString()} (Node ${process.version}). Synthetic data only.`);
log();

// ── 1. Clock sync ────────────────────────────────────────────────────────────
log('## 1. Clock sync error (device-estimated host time − true host time)');
log();
log('5-minute runs, ping every 250 ms after a 10-ping burst; errors sampled every 20 ms after 3 s warm-up.');
log();
log('| Network | Device clock | RTT p50 / p95 (ms) | abs(err) p50 | abs(err) p95 | abs(err) max | bias |');
log('|---|---|---|---|---|---|---|');
const syncByNet: Record<string, ReturnType<typeof simulateSync>> = {};
for (const net of NET_PROFILES) {
  let first = true;
  for (const [cname, clock] of Object.entries(clocks)) {
    const r = simulateSync(42 + net.name.length, net, clock, 5 * 60_000);
    if (first) syncByNet[net.name] = r;
    first = false;
    const rt = summarize(r.rtts);
    const ae = summarize(r.errors.map(Math.abs));
    const e = summarize(r.errors);
    log(`| ${net.name} | ${cname} | ${fmt(rt.p50)} / ${fmt(rt.p95)} | ${fmt(ae.p50, 2)} | ${fmt(ae.p95, 2)} | ${fmt(ae.max, 2)} | ${fmt(e.mean, 2)} |`);
  }
}
log();
log('Bias ≈ (up − down)/2 path asymmetry; it is invisible to NTP-style sync and is the floor of the error.');
log();

// ── 2. Ring detection ────────────────────────────────────────────────────────
log('## 2. Ring detection on synthetic strokes');
log();
log('4 sessions × 150 rings per row (600 rings), tempo 72–96 bpm, return swing between rings. Timestamp error = detected − true ring moment; *spread* = |error − median| (what remains after a per-device offset calibration). Latency = detection fired − true ring moment (matters only for sound on the phone).');
log();
log('| Ringer | Sensor | Axis calibrated | Detected | False | ts bias (ms) | ts spread p95 (ms) | latency p50 / p95 (ms) |');
log('|---|---|---|---|---|---|---|---|');
for (const sensor of [SENSOR_60HZ, SENSOR_100HZ]) {
  for (const prof of Object.keys(RINGERS) as (keyof typeof RINGERS)[]) {
    for (const cal of [false, true]) {
      const r = evalRings(prof, sensor, DEFAULT_RING_PARAMS, cal);
      const err = summarize(r.errors);
      const spread = summarize(centeredAbs(r.errors));
      const lat = summarize(r.latency);
      log(
        `| ${prof} | ${sensor.rateHz} Hz | ${cal ? 'yes' : 'no'} | ${fmt((100 * r.matched) / r.truth)} % | ${fmt((100 * r.extra) / r.truth)} % | ${fmt(err.p50)} | ${fmt(spread.p95)} | ${fmt(lat.p50)} / ${fmt(lat.p95)} |`,
      );
    }
  }
}
log();

log('### Threshold sweep (60 Hz, calibrated axis, all ringer profiles pooled; distractor false rings per minute)');
log();
log('| minDecel (deg/s²) | minPeakOmega (deg/s) | Detected | False (in session) | Distractor FP/min (any-axis) | Distractor FP/min (calibrated) |');
log('|---|---|---|---|---|---|');
for (const [minDecel, minPeak] of [
  [3000, 200],
  [4500, 200],
  [4500, 220],
  [6000, 200],
  [6000, 250],
  [9000, 300],
] as const) {
  const params = { ...DEFAULT_RING_PARAMS, minDecel, minPeakOmega: minPeak };
  let truth = 0;
  let matched = 0;
  let extra = 0;
  for (const prof of Object.keys(RINGERS) as (keyof typeof RINGERS)[]) {
    const r = evalRings(prof, SENSOR_60HZ, params, true, 2);
    truth += r.truth;
    matched += r.matched;
    extra += r.extra;
  }
  const fpAny = distractorFp(SENSOR_60HZ, params, false);
  const fpAx = distractorFp(SENSOR_60HZ, params, true);
  log(`| ${minDecel} | ${minPeak} | ${fmt((100 * matched) / truth)} % | ${fmt((100 * extra) / truth)} % | ${fmt(fpAny.perMin, 2)} | ${fmt(fpAx.perMin, 2)} |`);
}
log();
log('Distractors: slow tilts, hand-waving (1.5–3 Hz), picking the phone up, walking, bumps — 30 min per cell.');
log();

// ── 3. Clink test ────────────────────────────────────────────────────────────
log('## 3. Two-phone clink test (impact detector)');
log();
log('Same physical impacts seen by two phones with independent sampling phase. "Sampling only" isolates the sensor-rate quantisation; the network rows add each phone\'s simulated clock-sync error.');
log();
log('| Sensor | Network | Impacts detected (A / B) | Paired | abs(A−B) p50 (ms) | abs(A−B) p95 (ms) | per-phone ts spread p95 (ms) |');
log('|---|---|---|---|---|---|---|');
for (const sensor of [SENSOR_60HZ, SENSOR_100HZ]) {
  const sess = clinkSession(7, 200, sensor);
  const da = new ImpactDetector();
  const db = new ImpactDetector();
  const ea = sess.a.map((s) => da.push(s)).filter((e) => e !== null).map((e) => e!.t);
  const eb = sess.b.map((s) => db.push(s)).filter((e) => e !== null).map((e) => e!.t);
  const perPhone = matchNearest(sess.impacts, ea, 100).pairs.map((p) => p.diff);
  const nets: [string, ((h: number) => number) | null, ((h: number) => number) | null][] = [['sampling only', null, null]];
  for (const name of ['LAN, quiet', 'LAN, busy + power-save']) {
    const net = NET_PROFILES.find((n) => n.name === name)!;
    const sa = simulateSync(11, net, clocks['iPhone-like (1 ms timer, +40 ppm)'], sess.durationMs + 5000);
    const sb = simulateSync(12, net, clocks['Pixel-like (0.1 ms timer, −25 ppm)'], sess.durationMs + 5000);
    nets.push([name, sa.errorAt, sb.errorAt]);
  }
  for (const [name, fa, fb] of nets) {
    const ta = ea.map((t) => t + (fa ? fa(t + 4000) : 0));
    const tb = eb.map((t) => t + (fb ? fb(t + 4000) : 0));
    const m = matchNearest(ta, tb, 100);
    const d = summarize(m.pairs.map((p) => Math.abs(p.diff)));
    log(
      `| ${sensor.rateHz} Hz | ${name} | ${ea.length} / ${eb.length} of ${sess.impacts.length} | ${m.pairs.length} | ${fmt(d.p50)} | ${fmt(d.p95)} | ${fmt(summarize(centeredAbs(perPhone)).p95)} |`,
    );
  }
}
log();

// ── 4. End-to-end per-device timestamp error ────────────────────────────────
log('## 4. End-to-end synced timestamp error per ring (detector + clock sync)');
log();
log('Ring timestamp error (60 Hz, calibrated axis, all profiles) composed with the clock-sync error of each network; spread after removing the per-device median (i.e. after input-offset calibration).');
log();
log('| Network | spread p50 (ms) | spread p95 (ms) | spread p99 (ms) |');
log('|---|---|---|---|');
const pooled: number[] = [];
for (const prof of Object.keys(RINGERS) as (keyof typeof RINGERS)[]) pooled.push(...evalRings(prof, SENSOR_60HZ, DEFAULT_RING_PARAMS, true).errors);
for (const net of NET_PROFILES) {
  const s = syncByNet[net.name];
  const total = pooled.map((e, i) => e + s.errorAt(5000 + i * 400));
  const sp = summarize(centeredAbs(total));
  log(`| ${net.name} | ${fmt(sp.p50)} | ${fmt(sp.p95)} | ${fmt(sp.p99)} |`);
}
log();

const md = out.join('\n');
console.log(md);
writeFileSync(new URL('../results/sim-results.md', import.meta.url), md + '\n');
