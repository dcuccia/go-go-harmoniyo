const wss = new WebSocketServer({ noServer: true });

wss.on('connection', (ws: WebSocket, req: http.IncomingMessage) => {
  const conn: HostConn = {
    get open() {
      return ws.readyState === WebSocket.OPEN;
    },
    get connecting() {
      return ws.readyState === WebSocket.CONNECTING;
    },
    send: (text) => ws.send(text),
    close: (code, reason) => ws.close(code, reason),
    terminate: () => ws.terminate(),
  };
  const h = session.connect(conn, classifyWsRoute(req.headers, req.socket.remoteAddress));
  ws.on('message', (raw) => h.message(raw.toString(), now()));
  ws.on('close', () => h.closed());
});

session.start();

// ── listeners ───────────────────────────────────────────────────────────────

function attach(server: http.Server | https.Server): void {
  server.on('upgrade', (req, socket, head) => {
    if (new URL(req.url ?? '/', 'http://x').pathname !== '/hgp') {
      socket.destroy();
      return;
    }
    wss.handleUpgrade(req, socket, head, (ws) => wss.emit('connection', ws, req));
  });
}

function openBrowser(url: string): void {
  if (args['no-open']) return;
  try {
    if (process.platform === 'win32') spawn('cmd', ['/c', 'start', '', url], { detached: true, stdio: 'ignore' }).unref();
    else spawn(process.platform === 'darwin' ? 'open' : 'xdg-open', [url], { detached: true, stdio: 'ignore' }).unref();
  } catch {
    // ignore
  }
}

