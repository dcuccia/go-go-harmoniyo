/** Push re-assigned seat bells to their phones. */
function applySeats(seats: Seat[]): void {
  for (const s of seats) {
    const d = s.phoneId ? devices.get(s.phoneId) : undefined;
    if (!d) continue;
    d.bells = s.bells;
    session.sendAssign(d);
  }
  session.broadcastDevices();
}

