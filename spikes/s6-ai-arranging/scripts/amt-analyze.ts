// Analyse AMT accompaniments: note/instrument counts, range, chord-tone fit against the S5 chart's
// chords, and clashes (2nds/7ths/tritones) with the melody at accompaniment onsets.
//   node scripts/amt-analyze.ts → results/amt/analysis.md
import { existsSync, readFileSync, readdirSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';
import { S6_DIR } from '../src/llm.ts';
import { midiNotesSeconds } from '../src/midi-io.ts';
import { pitchName } from '../src/theory.ts';

const dir = join(S6_DIR, 'results', 'amt');
const r3 = (x: number) => Math.round(x * 1000) / 1000;
const rows: string[] = [];
for (const id of readdirSync(dir).filter((d) => existsSync(join(dir, d, 'accompaniment.mid'))).sort()) {
  const acc = midiNotesSeconds(readFileSync(join(dir, id, 'accompaniment.mid')));
  const mel = midiNotesSeconds(readFileSync(join(dir, id, 'melody.mid')));
  const chart = JSON.parse(readFileSync(join(S6_DIR, '..', 's5-chart-pipeline', 'charts', `${id}.json`), 'utf8'));
  const chords: { time: number; durSec: number; tones: number[]; symbol: string }[] = chart.harmony?.chords ?? [];
  const chordAt = (t: number) => chords.find((c) => c.time <= t + 1e-6 && t < c.time + c.durSec) ?? null;
  let tot = 0, fit = 0, onsets = 0, clash = 0;
  for (const n of acc) {
    const c = chordAt(n.time);
    tot += n.dur;
    if (c?.tones.includes(n.midi % 12)) fit += n.dur;
    const m = mel.find((x) => x.time <= n.time + 1e-6 && n.time < x.time + x.dur);
    if (m) {
      onsets++;
      if ([1, 2, 6, 10, 11].includes((((n.midi - m.midi) % 12) + 12) % 12)) clash++;
    }
  }
  const programs = new Map<number, number>();
  for (const n of acc) programs.set(n.program, (programs.get(n.program) ?? 0) + 1);
  const rep = JSON.parse(readFileSync(join(dir, id, 'report.json'), 'utf8'));
  const lo = Math.min(...acc.map((n) => n.midi));
  const hi = Math.max(...acc.map((n) => n.midi));
  const model = String(rep.model_dir ?? '').match(/music-(small|medium|large)-800k/)?.[0] ?? '?';
  rows.push(`| ${id} | ${model}, ${rep.device}, seed ${rep.args?.seed} | ${rep.melody_seconds} s | ${acc.length} | ${programs.size} (top: ${[...programs].sort((a, b) => b[1] - a[1]).slice(0, 4).map(([p, k]) => `${p}×${k}`).join(', ')}) | ${pitchName(lo)}–${pitchName(hi)} | ${r3(fit / tot)} | ${onsets ? r3(clash / onsets) : '–'} | ${rep.seconds?.load ?? '?'} / ${rep.seconds?.generate ?? '?'} s |`);
}
const md = [
  '# AMT accompaniment analysis (generated by `node scripts/amt-analyze.ts`)',
  '',
  'Chord fit = share of accompaniment note time on tones of the S5 chart chord sounding then (Deck the Halls: lead-sheet chords; The Holly and the Ivy: S5-inferred). Clash = share of accompaniment onsets that form a 2nd, 7th or tritone with the melody note sounding. Instruments are GM program numbers × notes.',
  '',
  '| Song | Run | Melody | Notes | Instruments | Range | Chord fit | Clash | Load / generate |',
  '|---|---|---|---|---|---|---|---|---|',
  ...rows,
  '',
].join('\n');
writeFileSync(join(dir, 'analysis.md'), md);
console.log(md);
